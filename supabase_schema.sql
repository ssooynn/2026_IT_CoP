-- 1) Extensions
create extension if not exists pgcrypto;

-- 2) Tables
create table if not exists public.judges (
  id uuid primary key default gen_random_uuid(),
  emp_no text not null unique,
  display_name text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.judge_sessions (
  user_id uuid primary key references auth.users(id) on delete cascade,
  judge_id uuid not null references public.judges(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.evaluation_forms (
  id uuid primary key default gen_random_uuid(),
  judge_id uuid not null unique references public.judges(id) on delete cascade,
  payload jsonb not null default '{"teams":{}}'::jsonb,
  status text not null default 'draft' check (status in ('draft','submitted')),
  updated_at timestamptz not null default now(),
  submitted_at timestamptz null
);

create table if not exists public.ranking_snapshots (
  id bigint generated by default as identity primary key,
  payload jsonb not null,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_emails (
  email text primary key,
  created_at timestamptz not null default now()
);

-- 3) Helper trigger for updated_at
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_judges_updated_at on public.judges;
create trigger trg_judges_updated_at
before update on public.judges
for each row execute function public.set_updated_at();

drop trigger if exists trg_judge_sessions_updated_at on public.judge_sessions;
create trigger trg_judge_sessions_updated_at
before update on public.judge_sessions
for each row execute function public.set_updated_at();

-- 4) Admin check function
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.admin_emails
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

-- 5) Judge session helper
create or replace function public.current_judge_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select judge_id
  from public.judge_sessions
  where user_id = auth.uid()
  limit 1;
$$;

-- 6) Judge login by employee number
create or replace function public.judge_login(p_emp_no text)
returns table (judge_id uuid, emp_no text, display_name text)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_judge public.judges%rowtype;
begin
  if auth.uid() is null then
    raise exception 'Anonymous or authenticated session is required.';
  end if;

  select *
    into v_judge
  from public.judges
  where emp_no = trim(p_emp_no)
    and is_active = true
  limit 1;

  if not found then
    return;
  end if;

  insert into public.judge_sessions (user_id, judge_id)
  values (auth.uid(), v_judge.id)
  on conflict (user_id)
  do update set judge_id = excluded.judge_id, updated_at = now();

  return query
  select v_judge.id, v_judge.emp_no, v_judge.display_name;
end;
$$;

-- 7) Admin view for responses
create or replace view public.evaluation_forms_admin as
select
  ef.id,
  ef.judge_id,
  j.emp_no as judge_emp_no,
  j.display_name as judge_display_name,
  ef.payload,
  ef.status,
  ef.updated_at,
  ef.submitted_at
from public.evaluation_forms ef
join public.judges j on j.id = ef.judge_id;

-- 8) RLS
alter table public.judges enable row level security;
alter table public.judge_sessions enable row level security;
alter table public.evaluation_forms enable row level security;
alter table public.ranking_snapshots enable row level security;
alter table public.admin_emails enable row level security;

-- Judges table: admin only
create policy if not exists judges_admin_all on public.judges
for all
using (public.is_admin())
with check (public.is_admin());

-- Judge sessions: self read, admin full
create policy if not exists judge_sessions_self_select on public.judge_sessions
for select
using (user_id = auth.uid() or public.is_admin());

create policy if not exists judge_sessions_admin_all on public.judge_sessions
for all
using (public.is_admin())
with check (public.is_admin());

-- Evaluation forms: judge owns own row, admin sees all
create policy if not exists evaluation_forms_select on public.evaluation_forms
for select
using (judge_id = public.current_judge_id() or public.is_admin());

create policy if not exists evaluation_forms_insert on public.evaluation_forms
for insert
with check (judge_id = public.current_judge_id() or public.is_admin());

create policy if not exists evaluation_forms_update on public.evaluation_forms
for update
using (judge_id = public.current_judge_id() or public.is_admin())
with check (judge_id = public.current_judge_id() or public.is_admin());

create policy if not exists evaluation_forms_delete_admin on public.evaluation_forms
for delete
using (public.is_admin());

-- Ranking snapshots: admin only
create policy if not exists ranking_snapshots_admin_all on public.ranking_snapshots
for all
using (public.is_admin())
with check (public.is_admin());

-- Admin emails: admin only
create policy if not exists admin_emails_admin_all on public.admin_emails
for all
using (public.is_admin())
with check (public.is_admin());

-- View grants / access
revoke all on public.evaluation_forms_admin from anon, authenticated;
grant select on public.evaluation_forms_admin to authenticated;

